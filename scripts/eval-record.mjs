#!/usr/bin/env node
// eval-record.mjs — project a Tessl eval run into plugins/<name>/evals/RESULTS.json.
//
// FR-TESSL-2 forbids a hand-written score, and it also removed a *generated* score record
// because nothing could keep it current for free. A run record is a different animal: an
// eval run is immutable history, not a projection of current state. A row describes what
// happened at one commit and does not rot when the skill changes — which is why every row
// carries plugin_version, skill_tree and scenario_tree, so a stale row is visibly stale
// rather than quietly wrong.
//
// Usage:
//   node scripts/eval-record.mjs <run-id> [<run-id>...]     # write per-plugin RESULTS.json
//   node scripts/eval-record.mjs --out <path> <run-id>...   # write one explicit file
//   node scripts/eval-record.mjs --stdout <run-id>          # print, write nothing
//
// Never records a run id, a workspace id, a user id or a local path: those are what
// tests/test-publication-safety.mjs Rule 3 exists to keep out of a public tree. The run is
// still identifiable — by plugin, scenario, commit and timestamp — without carrying one.
//
// Zero dependencies. Node >= 18.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

const NOTE =
  'Generated by scripts/eval-record.mjs from `tessl eval view <id> --json`. Scores are ' +
  'projected, never typed. classification is the one hand-written field and is required ' +
  'whenever a scenario did not complete.';

// A judgment, not a measurement — the one field a human fills in. The docs call an agent
// that does not finish normal behaviour, so it is a distinct outcome from a broken brief.
const CLASSIFICATIONS = ['scenario-defect', 'agent-non-completion', 'skill-gap'];

function git(args) {
  const r = spawnSync('git', args, { cwd: ROOT, encoding: 'utf8' });
  return r.status === 0 ? r.stdout.trim() : null;
}

// A git tree object id IS the canonical content hash of a directory, computed by git at the
// commit the run actually evaluated. Rolling our own would hash the working tree instead —
// a different tree, silently.
const treeAt = (commit, path) => git(['rev-parse', `${commit}:${path}`]);

function view(id) {
  const r = spawnSync('tessl', ['eval', 'view', id, '--json'], { cwd: ROOT, encoding: 'utf8' });
  if (r.status !== 0) {
    process.stderr.write(`tessl eval view ${id} failed:\n${r.stderr ?? ''}`);
    process.exit(1);
  }
  return JSON.parse(r.stdout);
}

const pct = (num, den) => (den > 0 ? Math.round((num / den) * 1000) / 10 : null);

function scoreOf(solutions) {
  const scored = solutions.filter((s) => Array.isArray(s.assessmentResults) && s.assessmentResults.length);
  if (!scored.length) return null;
  let got = 0;
  let max = 0;
  for (const s of scored) {
    for (const a of s.assessmentResults) {
      got += a.score ?? 0;
      max += a.max_score ?? 0;
    }
  }
  return pct(got, max);
}

function rowsFrom(envelope) {
  const a = envelope.data.attributes;
  const meta = a.metadata ?? {};
  const skill = meta.tileName ?? a.evalRunFixtures?.context?.path?.split('/').pop() ?? 'unknown';
  const commit = meta.commitHash ?? null;

  return (a.scenarios ?? []).map((sc) => {
    const scenario = sc.path ? sc.path.replace(/\/$/, '').split('/').pop() : 'unknown';
    const sols = sc.solutions ?? [];
    const baseline = sols.filter((s) => s.variant === 'baseline');
    const withPlugin = sols.filter((s) => s.variant !== 'baseline');

    const b = scoreOf(baseline);
    const w = scoreOf(withPlugin);
    const activated = [
      ...new Set(withPlugin.flatMap((s) => s.activation?.activatedSkills ?? [])),
    ].sort();

    // Three states, not two. An unscored run is not an incomplete one: --skip-scoring means
    // no scorer ever ran, which is the normal shape of an activation probe. Collapsing it
    // into "incomplete" would demand a failure classification for a run that did not fail.
    const unscored = a.skipScoring === true;
    const complete = !unscored && b !== null && w !== null;

    return {
      skill,
      plugin_version: meta.tileVersion ?? null,
      scenario,
      scenario_tree: commit && sc.path ? treeAt(commit, sc.path.replace(/\/$/, '')) : null,
      skill_tree: commit ? treeAt(commit, `plugins/${skill}/skills`) : null,
      context_commit: commit,
      model_reported: `${a.agent ?? '?'}:${a.model ?? '?'}`,
      forced_activation: a.skipForcedContextActivation !== true,
      runs: Math.max(baseline.length, withPlugin.length),
      baseline: b,
      with_plugin: w,
      lift_pp: complete ? Math.round((w - b) * 10) / 10 : null,
      activated,
      status: unscored ? 'unscored' : complete ? 'completed' : 'incomplete',
      // Left null on purpose. Why a run did not finish is a judgment, and a generator that
      // guesses it turns the harness's "an incomplete run is classified" check into a check
      // that this script filled a field in — which every row would pass, having said nothing.
      classification: null,
      t: a.createdAt ?? null,
    };
  });
}

function merge(existing, incoming) {
  const key = (r) => `${r.skill}\0${r.scenario}\0${r.t}`;
  const byKey = new Map(existing.map((r) => [key(r), r]));
  for (const r of incoming) {
    // A re-recorded run keeps whatever classification a human already wrote for it.
    const prior = byKey.get(key(r));
    if (prior?.classification) r.classification = prior.classification;
    byKey.set(key(r), r);
  }
  return [...byKey.values()].sort(
    (x, y) => x.skill.localeCompare(y.skill) || x.t.localeCompare(y.t) || x.scenario.localeCompare(y.scenario),
  );
}

function write(path, rows) {
  const existing = existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')).rows ?? [] : [];
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, `${JSON.stringify({ note: NOTE, rows: merge(existing, rows) }, null, 2)}\n`);
  process.stdout.write(`${path}: ${rows.length} row(s)\n`);
}

function main(argv) {
  let out = null;
  let toStdout = false;
  const ids = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out') out = argv[++i];
    else if (argv[i] === '--stdout') toStdout = true;
    else ids.push(argv[i]);
  }

  if (!ids.length) {
    process.stderr.write('usage: eval-record.mjs [--out <path>] [--stdout] <run-id>...\n');
    return 2;
  }

  const all = ids.flatMap((id) => rowsFrom(view(id)));

  if (toStdout) {
    process.stdout.write(`${JSON.stringify({ note: NOTE, rows: all }, null, 2)}\n`);
  } else if (out) {
    write(join(ROOT, out), all);
  } else {
    const bySkill = new Map();
    for (const r of all) {
      if (!bySkill.has(r.skill)) bySkill.set(r.skill, []);
      bySkill.get(r.skill).push(r);
    }
    for (const [skill, rows] of bySkill) write(join(ROOT, 'plugins', skill, 'evals', 'RESULTS.json'), rows);
  }
  return 0;
}

// Importing this file must not run the CLI, and must not terminate the importing process —
// the trap FR-OKF-6 fixed in okf.mjs. The harness imports CLASSIFICATIONS rather than
// restating it, which is only safe behind this guard.
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) process.exit(main(process.argv.slice(2)));

export { CLASSIFICATIONS, NOTE, rowsFrom, merge };
