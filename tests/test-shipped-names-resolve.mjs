#!/usr/bin/env node
// FR-CORPUS-1 — a name this repo SHIPS to a stranger's agent must resolve inside this repo.
//
// The corpus is the shipped INSTRUCTION text: tracked .md and .json under plugins/*/skills/**
// and plugins/*/hooks/**. Those bytes are instructions a reader's agent acts on, so a script
// name in them is a claim about this tree, and a generation marker in them is a claim about
// what this tool writes. Two rules, both anchored on the repository's own contents as the
// oracle rather than on a list of names typed into this file:
//
//   Rule A — every *.mjs basename the corpus names resolves to a tracked file.
//   Rule B — every `<!-- generated by ... -->` marker the corpus stamps is byte-identical
//            to one okf.mjs actually writes, imported from okf.mjs and never restated here.
//
// WHY INSTRUCTION TEXT AND NOT SOURCE. An instruction tells a reader to run something; a
// generator's source DEFINES the constants it matches against. okf.mjs legitimately carries
// both a deleted generator's basename and a retired marker, because recognising and adopting
// an old catalog is its job — scanning it would flag the guard's own oracle as two defects.
// Scoping the read to .md and .json is the honest fix, and it is not a hole: source is
// covered by its own AC suites (tests/test-okf-maintain.mjs, tests/test-okf-index-regen.mjs).
// This narrows what Rule A READS, never what it resolves AGAINST — a basename named in
// instruction text still resolves against the whole tracked tree, .mjs files included.
//
// WHY .mjs AND NOTHING ELSE. ADR-014 makes .mjs this repo's own executable extension: every
// hook, harness, CLI and skill script it ships is one. So a .mjs named in shipped text is a
// claim about OUR tree, while a .js/.ts/.py/.sh mention is illustrative code about the
// READER's project — `manage.py`, `server.js`, `setup.sh` are examples, not addresses.
// Measured before scoping: 78 of 109 distinct basenames across all extensions fail to
// resolve and only 2 are real defects, so an unscoped rule is 97% noise and would be
// switched off within a week. Scoped to .mjs, the noise is four CDN URLs and two named
// exemptions, both handled structurally below.
//
// THE CEILING, stated so nobody reads a green run as more than it is. A basename sweep sees
// only names that were WRITTEN. An instruction that omits the executable entirely — "run the
// generator", "regenerate the index" — names nothing, resolves nothing, and is invisible
// here; that omission is precisely what agentic-sdlc BUG-145 was filed for, and no sweep of
// this shape can find it. Scoping to .mjs also makes a retired .sh or .py helper invisible,
// which ADR-014 makes acceptable in this tree and nowhere else.
//
// Exit contract: 0 pass / 1 fail / 77 nothing evaluated.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Harness, skip } from './lib/harness.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// okf.mjs defines all three marker constants: it is Rule B's oracle, and it is source rather
// than instruction text, so the scope rule below keeps it out of what gets read. AC-5 pins
// that this exclusion is load-bearing rather than incidental.
const MARKER_SOURCE = 'plugins/okf-maintain/skills/okf-maintain/scripts/okf.mjs';

const CORPUS_PATHSPEC = ['plugins/*/skills/*', 'plugins/*/hooks/*'];

// Instruction text, not source. Stated as what is READ, never as what is skipped.
const INSTRUCTION_EXT = ['.md', '.json'];
const inScope = (rel) => INSTRUCTION_EXT.some((e) => rel.endsWith(e));

// Unresolvable .mjs basenames this repo is ENTITLED to name, each scoped to the one file that
// may name it — an unscoped entry would hide the same defect everywhere else in the tree.
const ALLOWED_UNRESOLVED = [
  {
    basename: 'extract-import-map.mjs',
    file: 'plugins/doc-this/skills/doc-this/references/ua-integration-guide.md',
    why: 'ships with the third-party Understand-Anything plugin, so it is correctly outside this repo',
  },
  {
    basename: 'okf-index-gen.mjs',
    file: 'plugins/okf-maintain/skills/okf-maintain/references/index-format.md',
    why: 'the marker table names the retired generator so a reader can identify its catalogs; being unresolvable is the fact it states',
  },
  {
    basename: 'okf-index-gen.mjs',
    file: 'plugins/okf-maintain/skills/okf-maintain/references/adoption.md',
    why: 'the adoption argument turns on which generator retired; naming it is history, not an address to run',
  },
];

// Files entitled to quote a marker this tool never writes. Scoped per file for the same reason
// Rule A's list is: okf-maintain OWNS the index grammar, so its references document all three
// markers, retired one included, and the bytes are the point of that documentation. No other
// skill is entitled — a marker quoted anywhere else is a template, which is how a shipped
// fallback came to stamp the retired generator's name into every index it hand-wrote.
const ALLOWED_MARKER_QUOTES = [
  'plugins/okf-maintain/skills/okf-maintain/references/index-format.md',
  'plugins/okf-maintain/skills/okf-maintain/references/adoption.md',
];

const git = (args) => spawnSync('git', args, { cwd: ROOT, encoding: 'utf8' });

const lines = (r) => (r.status === 0 ? r.stdout.split('\n').filter((l) => l !== '') : null);

const basenameOf = (p) => p.slice(p.lastIndexOf('/') + 1);

// ---------------------------------------------------------------------------
// The rules, as pure functions over (root, file list, oracle). The fixture and the real
// tree go through these identical code paths — a rule reachable only by the real tree
// cannot be mutation-tested, and an untested guard is a guard nobody has seen fire.
// ---------------------------------------------------------------------------

const MJS_TOKEN = /[A-Za-z0-9][A-Za-z0-9._-]*\.mjs\b/g;
const PATH_CHAR = /[A-Za-z0-9._~:@+\-/]/;

// The whole path-ish run around a match, so an address can be told from a bare basename.
function enclosingPath(line, start, end) {
  let a = start;
  let b = end;
  while (a > 0 && PATH_CHAR.test(line[a - 1])) a--;
  while (b < line.length && PATH_CHAR.test(line[b])) b++;
  return line.slice(a, b);
}

function readCorpus(root, files) {
  const out = [];
  for (const rel of files) {
    if (!inScope(rel)) continue;
    let text;
    try { text = readFileSync(join(root, rel), 'utf8'); } catch { continue; }
    out.push({ rel, lines: text.split('\n') });
  }
  return out;
}

function mjsMentions(docs) {
  const found = [];
  for (const { rel, lines: ls } of docs) {
    for (let i = 0; i < ls.length; i++) {
      const line = ls[i];
      MJS_TOKEN.lastIndex = 0;
      let m;
      while ((m = MJS_TOKEN.exec(line)) !== null) {
        const path = enclosingPath(line, m.index, m.index + m[0].length);
        found.push({ file: rel, line: i + 1, basename: m[0], path });
      }
    }
  }
  return found;
}

// A basename inside an absolute URL addresses somebody else's server, never this tree —
// structural, not an allowlist entry, so a new CDN import needs no maintenance here.
const isRemote = (mention) => mention.path.includes('://');

function ruleA({ mentions, resolvable, allowlist }) {
  const local = mentions.filter((m) => !isRemote(m));
  const exempt = (m) => allowlist.some((a) => a.basename === m.basename && a.file === m.file);
  return {
    examined: local.length,
    findings: local.filter((m) => !resolvable.has(m.basename) && !exempt(m)),
  };
}

const MARKER = /<!--\s*generated by[^>]*-->/g;

function markerStamps(docs) {
  const found = [];
  for (const { rel, lines: ls } of docs) {
    for (let i = 0; i < ls.length; i++) {
      MARKER.lastIndex = 0;
      let m;
      while ((m = MARKER.exec(ls[i])) !== null) found.push({ file: rel, line: i + 1, marker: m[0] });
    }
  }
  return found;
}

function ruleB({ stamps, accepted, retired, quotedBy = [] }) {
  return {
    examined: stamps.length,
    findings: stamps
      .filter((s) => !accepted.includes(s.marker) && !quotedBy.includes(s.file))
      .map((s) => ({ ...s, kind: s.marker === retired ? 'retired marker shipped as a template' : 'marker this tool never writes' })),
  };
}

// ---------------------------------------------------------------------------

const h = new Harness('FR-CORPUS-1 — shipped names resolve, shipped markers are ours');

if (git(['rev-parse', '--git-dir']).status !== 0) skip('git unavailable — the corpus cannot be enumerated');

let GEN_MARKER, GEN_MARKER_V1, RETIRED_V1_MARKER;
try {
  ({ GEN_MARKER, GEN_MARKER_V1, RETIRED_V1_MARKER } = await import(join(ROOT, MARKER_SOURCE)));
} catch (e) {
  skip(`${MARKER_SOURCE} could not be imported (${e.message}) — Rule B has no oracle`);
}
if (!GEN_MARKER || !GEN_MARKER_V1 || !RETIRED_V1_MARKER) {
  skip(`${MARKER_SOURCE} no longer exports all three marker constants — Rule B has no oracle`);
}

const corpusFiles = lines(git(['ls-files', '--', ...CORPUS_PATHSPEC]));
const trackedAll = lines(git(['ls-files']));
if (!corpusFiles || !trackedAll) skip('git ls-files failed — the corpus cannot be enumerated');

// Resolution reads the WHOLE tracked tree, not the narrowed corpus: a name written in
// instruction text resolves against every file this repo ships, .mjs included.
const RESOLVABLE = new Set(trackedAll.map(basenameOf));
const scoped = corpusFiles.filter(inScope);
const docs = readCorpus(ROOT, corpusFiles);
const mentions = mjsMentions(docs);
const stamps = markerStamps(docs);

h.section('AC-1  the corpus is the shipped instruction text, and it is not empty');
// A scan that reads nothing reports PASS. Assert the population before trusting any verdict.
h.check(`${corpusFiles.length} tracked file(s) under plugins/*/{skills,hooks}, ${scoped.length} of them ${INSTRUCTION_EXT.join('/')}`,
  scoped.length > 0, 'the corpus is empty — both rules below would pass having read nothing');
h.check('every corpus path is tracked by git (an untracked node_modules ships nothing and must not appear)',
  corpusFiles.every((f) => !f.includes('/node_modules/')));
h.check(`readable: ${docs.length} of ${scoped.length} in-scope file(s) opened`, docs.length === scoped.length,
  `${scoped.length - docs.length} file(s) could not be read`);
h.check(`resolution still reads the whole tracked tree (${RESOLVABLE.size} distinct basename(s)), which the narrowed read scope must not shrink`,
  RESOLVABLE.size > scoped.length);

h.section('AC-2  Rule A examined a non-empty population');
const a = ruleA({ mentions, resolvable: RESOLVABLE, allowlist: ALLOWED_UNRESOLVED });
h.check(`${mentions.length} .mjs mention(s) found, ${a.examined} of them local to this tree`,
  a.examined > 0, 'no .mjs name was examined — Rule A proves nothing');

h.section('AC-3  Rule A — every .mjs basename the corpus names resolves to a tracked file');
for (const f of a.findings) {
  h.bad(`${f.file}:${f.line} names '${f.basename}' — no tracked file in this repo carries that basename`,
    `as written: ${f.path}`);
}
h.check(`all ${a.examined} local .mjs mention(s) resolve`, a.findings.length === 0,
  `${a.findings.length} unresolved`);

h.section('AC-4  each exemption is load-bearing and scoped to one file');
// An allowlist entry nothing matches is dead weight that reads as protection; an entry with
// no file scope would hide the same defect everywhere else.
const unresolvedRaw = mentions.filter((m) => !isRemote(m) && !RESOLVABLE.has(m.basename));
for (const entry of ALLOWED_UNRESOLVED) {
  const hits = unresolvedRaw.filter((m) => m.basename === entry.basename && m.file === entry.file);
  h.check(`'${entry.basename}' in ${entry.file} really is unresolvable (${hits.length} mention(s)) — ${entry.why}`,
    hits.length >= 1, 'the exemption matches nothing; delete it rather than leave it reading as protection');
}
h.check('every exemption names the one file entitled to it', ALLOWED_UNRESOLVED.every((e) => typeof e.file === 'string' && e.file.length > 0));

h.section('AC-5  Rule B examined a non-empty population, and the source scope rule is load-bearing');
h.check(`${stamps.length} generation marker(s) found in the corpus`, stamps.length > 0,
  'no marker was examined — Rule B proves nothing');
// The instruction-text scope is what keeps the oracle out of its own verdict. Prove it is
// doing real work: the defining module is out of scope AND really does carry both the
// deleted generator's basename and the retired marker, so a naive scan would flag it twice.
{
  const src = readFileSync(join(ROOT, MARKER_SOURCE), 'utf8');
  h.check(`${MARKER_SOURCE} is source, not instruction text, so it is outside the read scope`, !inScope(MARKER_SOURCE));
  h.check('and it really does define the retired marker and name the deleted generator — a naive scan would report the oracle as two defects',
    src.includes('RETIRED_V1_MARKER') && src.includes('okf-index-gen.mjs'));
}

h.section('AC-6  Rule B — every stamped marker is byte-identical to one this tool writes');
const b = ruleB({ stamps, accepted: [GEN_MARKER, GEN_MARKER_V1], retired: RETIRED_V1_MARKER, quotedBy: ALLOWED_MARKER_QUOTES });
for (const f of b.findings) {
  h.bad(`${f.file}:${f.line} stamps a ${f.kind}`, `as written: ${f.marker}`);
}
h.check(`all ${b.examined} stamped marker(s) match GEN_MARKER or GEN_MARKER_V1`, b.findings.length === 0,
  `${b.findings.length} drifted`);

// ---------------------------------------------------------------------------
// Mutation. A green suite says nothing about a guard nobody has watched fire, so both rules
// are run over a planted-defect tree and a benign tree through the same functions above.
// ---------------------------------------------------------------------------

function fixture(files) {
  const dir = h.mkTemp('fr-corpus-1-');
  const rels = [];
  for (const [rel, body] of Object.entries(files)) {
    const abs = join(dir, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, body, 'utf8');
    rels.push(rel);
  }
  return { dir, rels };
}

h.section('AC-7  mutation — a planted retired basename makes Rule A fire');
const bad = fixture({
  'skills/x/references/stale.md': 'Regenerate with `node scripts/okf-index-gen.mjs index .`\n',
  'skills/x/references/moved.md': 'Its harness is `test-build-manifest.mjs`.\n',
});
const badDocs = readCorpus(bad.dir, bad.rels);
const badA = ruleA({ mentions: mjsMentions(badDocs), resolvable: new Set(['okf.mjs']), allowlist: [] });
h.equal('Rule A reports both planted unresolvable basenames', badA.findings.length, 2);
h.check('the finding names the file and line a reader would open',
  badA.findings.every((f) => f.line > 0 && f.file.endsWith('.md')));

// The scope rule must be APPLIED, not merely declared: the identical defect body in a .mjs
// is source and must never be read. Without this leg, a scope rule that silently dropped
// everything would still look green above.
const sourceOnly = fixture({ 'skills/x/scripts/gen.mjs': "const RETIRED = 'okf-index-gen.mjs';\n" });
const sourceDocs = readCorpus(sourceOnly.dir, sourceOnly.rels);
h.equal('a .mjs carrying the same defect body is source and is not read', sourceDocs.length, 0);
h.equal('so Rule A reports nothing for it', ruleA({ mentions: mjsMentions(sourceDocs), resolvable: new Set(), allowlist: [] }).findings.length, 0);

h.section('AC-8  mutation — a drifted and a retired marker both make Rule B fire');
const badMarkers = fixture({
  'skills/x/drifted.md': '<!-- generated by some-other-tool.mjs - do not edit -->\n',
  'skills/x/retired.md': `${RETIRED_V1_MARKER}\n`,
});
const badB = ruleB({
  stamps: markerStamps(readCorpus(badMarkers.dir, badMarkers.rels)),
  accepted: [GEN_MARKER, GEN_MARKER_V1],
  retired: RETIRED_V1_MARKER,
});
h.equal('Rule B reports both planted markers', badB.findings.length, 2);
h.check('the retired marker is named as retired, not merely as unknown drift',
  badB.findings.some((f) => f.kind === 'retired marker shipped as a template'));
h.check('the unknown marker is named as drift',
  badB.findings.some((f) => f.kind === 'marker this tool never writes'));

h.section('AC-9  control — a benign tree makes NEITHER rule fire');
// A rule that matches everything and a rule that matches nothing both look green from one
// side. This is the other side.
// Every fixture file is .md or .json. A canary written to a .mjs would fall outside the read
// scope and silently stop proving anything — the fail-open this whole suite is about.
const good = fixture({
  'skills/x/ok.md': 'Run `node plugins/okf-maintain/skills/okf-maintain/scripts/okf.mjs index .`\n',
  'skills/x/hooks.json': '{ "command": "node \\"${CLAUDE_PLUGIN_ROOT}/hooks/okf-index-regen.mjs\\"" }\n',
  'skills/x/cdn.md': 'Loaded from `https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.esm.min.mjs`.\n',
  'skills/x/other-langs.md': 'Your project runs `manage.py migrate`, `server.js`, `setup.sh`.\n',
  'skills/x/vendored.md': 'UA ships `extract-import-map.mjs`.\n',
  'skills/x/index.md': `${GEN_MARKER}\n\n| Document | Description |\n`,
  'skills/x/v1.md': `${GEN_MARKER_V1}\n`,
});
const goodDocs = readCorpus(good.dir, good.rels);
h.equal('every benign fixture file is in scope and was read', goodDocs.length, good.rels.length);
const goodMentions = mjsMentions(goodDocs);
const goodAllow = [{ basename: 'extract-import-map.mjs', file: 'skills/x/vendored.md', why: 'fixture stand-in for the third-party plugin' }];
const goodA = ruleA({ mentions: goodMentions, resolvable: new Set(['okf.mjs', 'okf-index-regen.mjs']), allowlist: goodAllow });
h.equal('Rule A fires on nothing benign', goodA.findings.length, 0);
h.equal('the CDN mention was seen and classified remote, not merely absent', goodMentions.filter(isRemote).length, 1);
h.check('it nevertheless examined the benign local mentions rather than skipping them', goodA.examined >= 3,
  `examined ${goodA.examined}`);
const goodB = ruleB({
  stamps: markerStamps(goodDocs),
  accepted: [GEN_MARKER, GEN_MARKER_V1],
  retired: RETIRED_V1_MARKER,
});
h.equal('Rule B fires on nothing benign', goodB.findings.length, 0);
h.equal('it nevertheless examined both benign markers', goodB.examined, 2);

h.section('AC-10  the exemption is scoped, proven by moving it');
// The same benign tree with the exemption pointed at a different file must fire, or "scoped
// to one file" is decoration.
const movedAllow = [{ ...goodAllow[0], file: 'skills/x/ok.md' }];
const movedA = ruleA({ mentions: goodMentions, resolvable: new Set(['okf.mjs', 'okf-index-regen.mjs']), allowlist: movedAllow });
h.equal('an exemption aimed at the wrong file does not silence the mention', movedA.findings.length, 1);

h.section('AC-11  a marker quote is entitled per file, and only okf-maintain is entitled');
// The marker-quote exemption is the one that could silence BUG-007 itself, so it is canaried
// in both directions on the REAL tree's entitlement list rather than on a fixture list.
const QUOTER = 'plugins/okf-maintain/skills/okf-maintain/references/index-format.md';
const STAMPER = 'plugins/doc-this/skills/doc-this-promote/references/okf-conformance.md';
const quoteFixture = fixture({
  [QUOTER]: `| \`${RETIRED_V1_MARKER}\` | Never | a documented row |\n`,
  [STAMPER]: `${RETIRED_V1_MARKER}\n`,
});
const quoteStamps = markerStamps(readCorpus(quoteFixture.dir, quoteFixture.rels));
h.equal('both quotes were seen', quoteStamps.length, 2);
const quoteB = ruleB({
  stamps: quoteStamps,
  accepted: [GEN_MARKER, GEN_MARKER_V1],
  retired: RETIRED_V1_MARKER,
  quotedBy: ALLOWED_MARKER_QUOTES,
});
h.equal('the grammar owner may quote the retired marker', quoteB.findings.length, 1);
h.check('and a promote reference stamping the same bytes still fires - this is BUG-007',
  quoteB.findings[0] && quoteB.findings[0].file === STAMPER,
  `fired on ${quoteB.findings[0] && quoteB.findings[0].file}`);
h.equal('with no entitlement at all, both fire',
  ruleB({ stamps: quoteStamps, accepted: [GEN_MARKER, GEN_MARKER_V1], retired: RETIRED_V1_MARKER }).findings.length, 2);
h.check('every entitled path is a real tracked file, not a stale exemption',
  ALLOWED_MARKER_QUOTES.every((f) => corpusFiles.includes(f)),
  ALLOWED_MARKER_QUOTES.join(', '));

h.section('AC-12  the suite is discoverable by tests/run-all.mjs');
h.check("filename matches run-all.mjs's one discovery rule (^test-.*\\.mjs$)",
  /^test-.*\.mjs$/.test(basenameOf(fileURLToPath(import.meta.url))));

h.done();
